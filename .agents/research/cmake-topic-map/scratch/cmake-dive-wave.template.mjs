function verify(group) {
  const path = RESEARCH + '/cmake-' + group + '.md'
  const ledger = RESEARCH + '/cmake-' + group + '/verification-wave' + WAVE + '.md'
  return agent(
    `Model rationale: opus — adversarial verification of version floors and MUST rules before they become enforced configuration; the CPS round showed cheaper dives get about one version claim in seven wrong.

${CONTEXT}

You are the VERIFIER for ${path}. Try to REFUTE its load-bearing claims, then correct the consolidation in place.

1. Read ${path} in full. List every MUST rule and every claim of the form "<tool> <version> does/introduced/removed/deprecated X" (version floors in rule rows count).
2. For each, re-check it against the strongest evidence you can get cheaply: re-run it on the local CMake binaries (3.31, 4.3, 4.4) with a scratch project under ${MEASURE}/verify-${group}/ where a 20-line project settles it; otherwise re-fetch the primary source (CMake Help/*.rst at the relevant tag on gitlab.kitware.com raw; the tool's docs, changelog or source). Also run every MUST rule's verification command against a tiny planted violation and a tiny clean case where that is feasible, to prove the check can go red and stays green on clean input.
3. Classify each: CONFIRMED (evidence quoted), CORRECTED (what was wrong, what is true, evidence), or UNVERIFIABLE (what you tried). Default to UNVERIFIABLE, never CONFIRMED, when you could not check it.
4. Write the ledger to ${ledger} (YAML frontmatter: title, verifies, model: opus, date: ${DATE}; sections "## Ledger" as a table # | ID or claim | verdict | evidence | note, "## Verification commands exercised" with the planted-violation outcome per command, "## Unverifiable").
5. Edit ${path} in place for every CORRECTED item: change the rule text, floor, severity or verification; never renumber or delete an ID (retire it in place with a one-line reason if it must go); add a "## Revision log" line per change tagged "verify wave ${WAVE}"; add verified: ${DATE} to the frontmatter.

Modify only ${path}, ${ledger} and files under ${MEASURE}/verify-${group}/. Return the structured receipt.`,
    { label: 'verify:' + group, phase: 'Verify', model: 'opus', effort: 'high', schema: VERIFY_SCHEMA },
  )
}

// ---------------------------------------------------------------- Run
const groups = {}
for (const item of SELECTION) (groups[item.group] = groups[item.group] || []).push(item)
const entries = Object.entries(groups)
log('Wave ' + WAVE + ': ' + SELECTION.length + ' dives across ' + entries.length + ' groups (' + entries.map(([g, i]) => g + 'x' + i.length).join(', ') + '); revising: ' + (entries.filter(([g]) => EXISTING.has(g)).map(([g]) => g).join(', ') || 'none'))

const results = await pipeline(
  entries,
  ([group, items]) => parallel(items.map(item => () => dive(item).then(r => ({ slug: item.slug, ...(r || {}), ok: !!r })))),
  (dives, [group, items]) => {
    const ok = dives.filter(Boolean).filter(d => d.ok)
    if (!ok.length) { log('SKIP consolidate:' + group + ' — every dive dropped'); return { group, dives, consolidation: null } }
    if (ok.length < items.length) log('consolidate:' + group + ' proceeding with ' + ok.length + '/' + items.length + ' dives')
    return consolidate(group, items).then(c => ({ group, dives, consolidation: c }))
  },
  (r) => {
    if (!r || !r.consolidation) return r
    return verify(r.group).then(v => ({ ...r, verification: v }))
  },
)

const out = results.filter(Boolean)
const surprises = out.flatMap(r => (r.dives || []).filter(Boolean).flatMap(d => (d.surprises || []).map(s => r.group + '/' + d.slug + ': ' + s)))
const another = out.flatMap(r => ((r.consolidation && r.consolidation.needs_another_round) || []).map(s => r.group + ': ' + s))
const corrected = out.flatMap(r => ((r.verification && r.verification.corrected) || []).map(s => r.group + ': ' + s))
const musts = out.reduce((n, r) => n + ((r.consolidation && r.consolidation.must_count) || 0), 0)
log('Wave ' + WAVE + ' done: ' + out.filter(r => r.consolidation).length + '/' + entries.length + ' groups consolidated · ' + musts + ' MUST rules · ' + surprises.length + ' surprises · ' + another.length + ' follow-ups · ' + corrected.length + ' verifier corrections')
return { wave: WAVE, groups: out, surprises, needs_another_round: another, verifier_corrections: corrected, must_count: musts }
