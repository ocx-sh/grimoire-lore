def is_vendored(relpath):
    parts = relpath.split(os.sep)
    return any(p in VENDORED_COMPONENTS for p in parts)


def is_scaffold(relpath):
    parts = [p.lower() for p in relpath.split(os.sep)]
    return any(p in SCAFFOLD_COMPONENTS for p in parts)


def is_kitware_excluded(repo, relpath):
    if repo != "Kitware__CMake":
        return False
    return relpath.startswith("Tests" + os.sep) or relpath.startswith("Help" + os.sep)


def iter_files():
    for repo in sorted(os.listdir(CORPUS)):
        rd = os.path.join(CORPUS, repo)
        if not os.path.isdir(os.path.join(rd, ".git")):
            continue
        for root, dirs, files in os.walk(rd):
            if os.sep + ".git" in root or root.endswith(os.sep + ".git"):
                dirs[:] = []
                continue
            for f in files:
                if f == "CMakeLists.txt" or f.endswith(".cmake"):
                    full = os.path.join(root, f)
                    rel = os.path.relpath(full, rd)
                    yield repo, rel, full


UNQUOTED_VAR_COMPARE_RE = re.compile(
    r"(?<![A-Za-z0-9_}])\$\{[A-Za-z_][A-Za-z0-9_]*\}(?![A-Za-z0-9_{])"
    r'[^"]{0,40}?\b(STREQUAL|MATCHES|EQUAL|VERSION_(LESS|GREATER|EQUAL)[A-Z_]*)\b'
)
QUOTED_BEFORE_RE = re.compile(r'"\s*\$\{[A-Za-z_][A-Za-z0-9_]*\}\s*"')
BARE_FOREACH_RE = re.compile(r"^\s*[A-Za-z_][A-Za-z0-9_]*\s+\$\{[A-Za-z_][A-Za-z0-9_]*\}\s*$")
HAND_JOINED_LIST_RE = re.compile(r'"[^"\n]*;[^"\n]*"')
PARSE_ARGV_RE = re.compile(r"^\s*PARSE_ARGV\b")

WANTED = {
    "if", "elseif", "while", "foreach", "macro", "endmacro", "function",
    "endfunction", "option", "cmake_parse_arguments", "set", "separate_arguments",
}


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--demo":
        demo()
        return

    per_repo = defaultdict(lambda: defaultdict(int))
    examples = defaultdict(list)
    EXAMPLE_CAP = 60

    def add_example(axis, repo, relpath, line, snippet):
        if len(examples[axis]) < EXAMPLE_CAP:
            examples[axis].append(f"{repo}:{relpath}:{line}: {snippet}")

    file_count = defaultdict(int)
    kitware_excluded_count = 0
    generated_file_count = defaultdict(int)
    option_names = defaultdict(set)

    for repo, relpath, full in iter_files():
        if is_kitware_excluded(repo, relpath):
            kitware_excluded_count += 1
            continue
        vendored = is_vendored(relpath)
        scaffold = is_scaffold(relpath)
        try:
            with open(full, "r", errors="replace") as fh:
                raw = fh.read()
        except OSError:
            continue

        head = "\n".join(raw.split("\n")[:40])
        if GENERATED_BANNER_RE.search(head):
            generated_file_count[repo] += 1
            continue

        bucket = "vendored" if vendored else ("scaffold" if scaffold else "core")
        file_count[repo] += 1

        cleaned = clean_text(raw)
        calls = extract_calls(cleaned, WANTED)

        # ---- macro bodies (M-C-04): text span from macro( to its matching
        # endmacro(, found positionally (macros don't nest in the corpus in
        # a way that defeats a simple next-endmacro-after-this-macro scan;
        # verified by hand on the sample below).
        macro_starts = [(ln, oneline) for (ln, nm, oneline, raw_a) in calls if nm.lower() == "macro"]
        endmacro_lines = sorted(ln for (ln, nm, _, _) in calls if nm.lower() == "endmacro")
        lines_arr = cleaned.split("\n")
        for (mstart_line, monel) in macro_starts:
            per_repo[(repo, bucket)]["macro_total"] += 1
            close = next((e for e in endmacro_lines if e >= mstart_line), None)
            body = "\n".join(lines_arr[mstart_line - 1 : close]) if close else "\n".join(lines_arr[mstart_line - 1 :])
            has_return = bool(re.search(r"\breturn\s*\(", body))
            has_argn = bool(re.search(r"\$\{ARGN\}|\bARGN\b", body))
            has_bare_set_novar = bool(
                re.search(r"\bset\s*\(\s*[A-Za-z_][A-Za-z0-9_]*\s", body)
                and not re.search(r"PARENT_SCOPE", body)
            )
            flags = []
            if has_return:
                flags.append("return")
                per_repo[(repo, bucket)]["macro_with_return"] += 1
            if has_argn:
                flags.append("argn")
                per_repo[(repo, bucket)]["macro_with_argn"] += 1
            if has_bare_set_novar:
                flags.append("bare_set")
            if flags:
                per_repo[(repo, bucket)]["macro_flagged_any"] += 1
                name_m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)", monel)
                mname = name_m.group(1) if name_m else "?"
                add_example(
                    "M-C-04-flagged", repo, relpath, mstart_line,
                    f"macro({mname}) [{'+'.join(flags)}]",
                )

        for line_no, name, oneline, raw_args in calls:
            lname = name.lower()

            if lname in ("if", "elseif", "while"):
                per_repo[(repo, bucket)][f"{lname}_total"] += 1
                stripped_quoted = QUOTED_BEFORE_RE.sub('"Q"', raw_args)
                if UNQUOTED_VAR_COMPARE_RE.search(stripped_quoted):
                    per_repo[(repo, bucket)]["unquoted_if_compare"] += 1
                    add_example("M-C-03-unquoted-if", repo, relpath, line_no, f"{lname}({oneline[:100]})")

            elif lname == "foreach":
                per_repo[(repo, bucket)]["foreach_total"] += 1
                if BARE_FOREACH_RE.match(oneline):
                    per_repo[(repo, bucket)]["foreach_bare"] += 1
                    add_example("M-C-03-bare-foreach", repo, relpath, line_no, f"foreach({oneline[:100]})")

            elif lname == "option":
                toks = oneline.split()
                if toks:
                    optname = toks[0].strip('"')
                    per_repo[(repo, bucket)]["option_total"] += 1
                    option_names[(repo, bucket)].add(optname)
                    if optname.upper().startswith("CMAKE_"):
                        per_repo[(repo, bucket)]["option_cmake_prefixed"] += 1
                        add_example("M-C-09-cmake-prefixed", repo, relpath, line_no, f"option({oneline[:100]})")

            elif lname == "cmake_parse_arguments":
                per_repo[(repo, bucket)]["cpa_total"] += 1
                is_parse_argv = bool(PARSE_ARGV_RE.match(raw_args.strip()))
                if is_parse_argv:
                    per_repo[(repo, bucket)]["cpa_parse_argv"] += 1
                    prefix_m = re.match(r"^\s*PARSE_ARGV\s+\d+\s+([A-Za-z_][A-Za-z0-9_]*)", raw_args)
                else:
                    per_repo[(repo, bucket)]["cpa_argn_form"] += 1
                    prefix_m = re.match(r"^\s*\"?([A-Za-z_][A-Za-z0-9_]*)\"?", raw_args)
                prefix = prefix_m.group(1) if prefix_m else None
                # look at the next ~60 lines (or to end of enclosing function/
                # macro) for the two named checks
                window = "\n".join(lines_arr[line_no - 1 : line_no + 59])
                checks_unparsed = bool(prefix and re.search(rf"\b{re.escape(prefix)}_UNPARSED_ARGUMENTS\b", window))
                checks_missing = bool(prefix and re.search(rf"\b{re.escape(prefix)}_KEYWORDS_MISSING_VALUES\b", window))
                if not is_parse_argv:
                    if not checks_unparsed:
                        per_repo[(repo, bucket)]["cpa_argn_no_unparsed_check"] += 1
                    if not checks_missing:
                        per_repo[(repo, bucket)]["cpa_argn_no_missing_check"] += 1
                    if not (checks_unparsed and checks_missing):
                        add_example(
                            "M-C-06-argn-unchecked", repo, relpath, line_no,
                            f"cmake_parse_arguments({oneline[:80]}) unparsed={checks_unparsed} missing={checks_missing}",
                        )

            elif lname == "set":
                if HAND_JOINED_LIST_RE.search(raw_args):
                    per_repo[(repo, bucket)]["hand_joined_list"] += 1
                    add_example("M-C-08-hand-joined", repo, relpath, line_no, f"set({oneline[:100]})")

            elif lname == "separate_arguments":
                per_repo[(repo, bucket)]["separate_arguments_use"] += 1
                add_example("M-C-08-separate-arguments", repo, relpath, line_no, f"separate_arguments({oneline[:100]})")

    for (repo, bucket), names in option_names.items():
        d = per_repo[(repo, bucket)]
        pref_count = defaultdict(int)
        for nm in names:
            if "_" in nm:
                pref_count[nm.split("_")[0].upper()] += 1
        if pref_count:
            pfx, cnt = max(pref_count.items(), key=lambda kv: kv[1])
        else:
            pfx, cnt = None, 0
        d["option_distinct_names"] = len(names)
        d["option_dominant_prefix"] = pfx or ""
        d["option_dominant_prefix_count"] = cnt
        unprefixed = sum(1 for nm in names if not (pfx and nm.upper().startswith(pfx + "_")))
        d["option_unprefixed_estimate"] = unprefixed

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "per_repo_counts.json"), "w") as f:
        json.dump({f"{r}|{b}": dict(d) for (r, b), d in per_repo.items()}, f, indent=1, sort_keys=True)
    with open(os.path.join(OUT_DIR, "examples.json"), "w") as f:
        json.dump(examples, f, indent=1, sort_keys=True)
    with open(os.path.join(OUT_DIR, "exclusions_summary.json"), "w") as f:
        json.dump(
            {
                "kitware_tests_help_files_excluded": kitware_excluded_count,
                "generated_files_excluded_per_repo": dict(generated_file_count),
                "firstparty_plus_vendored_files_scanned_by_repo": dict(file_count),
            },
            f,
            indent=1,
            sort_keys=True,
        )
    print("done", file=sys.stderr)


if __name__ == "__main__":
    main()
