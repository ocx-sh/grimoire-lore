#!/usr/bin/env python3
"""
Multi-line-aware CMake call parser for CMK-TGT / CMK-LANG per-repo evidence.
Extends .agents/research/cmake-audit/scratch/deps-cmake-calls.py's paren-
balanced, comment-stripped call extractor into one pass that measures:

  M-E-01  target_link_libraries without PUBLIC/PRIVATE/INTERFACE
  M-E-02  directory-scoped include_directories/add_definitions/
          add_compile_options/link_directories/link_libraries
  M-E-03  set()/string(APPEND) on CMAKE_C_FLAGS / CMAKE_CXX_FLAGS
  M-E-04  CMAKE_CXX_STANDARD set() vs target_compile_features cxx_std_NN
  M-E-10  file(GLOB|GLOB_RECURSE) feeding add_library/add_executable/
          target_sources, with/without CONFIGURE_DEPENDS
  M-E-11  literal -Werror / /WX vs CMAKE_COMPILE_WARNING_AS_ERROR
  M-C-03  unquoted ${var} in if()/elseif()/while() comparisons;
          bare foreach(x ${list})
  M-C-07  generator expressions ($<...>) inside message()/if()/string()
  M-C-09  option() names without project prefix; user vars named CMAKE_*

Exclusions (reported separately, never mixed into the main counts):
  - Kitware__CMake/Tests/**, Kitware__CMake/Help/**
  - any path component: contrib, third_party, third-party, deps, _deps
  - any file whose first 40 lines contain an "automatically generated"
    style banner (case-insensitive), e.g. grpc's generated build files

NEVER pipes into `grep -q` under pipefail (wave-1's SIGPIPE trap) -- this
is a single Python process; no shell pipeline touches the corpus walk.
"""
import json
import os
import re
import sys
from collections import defaultdict

CORPUS = "/home/mherwig/.cache/research-lang/exemplars/cmake"
OUT_DIR = "/home/mherwig/.cache/cmake-measure-scratch/consumable-library-targets"

VENDORED_COMPONENTS = {"contrib", "third_party", "third-party", "deps", "_deps"}
GENERATED_BANNER_RE = re.compile(
    r"automatically generated|do not edit|generated by cmake|@generated|autogenerated",
    re.IGNORECASE,
)

CALL_NAME_RE = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")

DIRECTORY_SCOPED = {
    "include_directories",
    "add_definitions",
    "add_compile_options",
    "link_directories",
    "link_libraries",
}
TARGET_KEYWORDS = {"PUBLIC", "PRIVATE", "INTERFACE"}


def strip_comment(line):
    out, inq, esc = [], False, False
    for ch in line:
        if esc:
            out.append(ch)
            esc = False
            continue
        if ch == "\\" and inq:
            out.append(ch)
            esc = True
            continue
        if ch == '"':
            inq = not inq
        if ch == "#" and not inq:
            break
        out.append(ch)
    return "".join(out)


def is_vendored(relpath):
    parts = relpath.split(os.sep)
    return any(p in VENDORED_COMPONENTS for p in parts)


SCAFFOLD_COMPONENTS = {"example", "examples", "test", "tests", "testing", "fixture", "fixtures", "sample", "samples"}


def is_scaffold(relpath):
    parts = [p.lower() for p in relpath.split(os.sep)]
    return any(p in SCAFFOLD_COMPONENTS for p in parts)


def is_kitware_excluded(repo, relpath):
    if repo != "Kitware__CMake":
        return False
    return relpath.startswith("Tests" + os.sep) or relpath.startswith("Help" + os.sep)


def iter_files():
    for repo in sorted(os.listdir(CORPUS)):
        rd = os.path.join(CORPUS, repo)
        if not os.path.isdir(os.path.join(rd, ".git")):
            continue
        for root, dirs, files in os.walk(rd):
            if os.sep + ".git" in root or root.endswith(os.sep + ".git"):
                dirs[:] = []
                continue
            for f in files:
                if f == "CMakeLists.txt" or f.endswith(".cmake"):
                    full = os.path.join(root, f)
                    rel = os.path.relpath(full, rd)
                    yield repo, rel, full


def extract_calls(cleaned_text, wanted_lower):
    """Balanced-paren, multi-line-aware extraction of calls whose name
    (case-insensitively) is in wanted_lower. Returns list of
    (line_no, name_as_written, args_oneline, args_raw_with_newlines)."""
    out = []
    for m in CALL_NAME_RE.finditer(cleaned_text):
        name = m.group(1)
        if name.lower() not in wanted_lower:
            continue
        start = m.end() - 1
        depth = 0
        i = start
        n = len(cleaned_text)
        while i < n:
            c = cleaned_text[i]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        args_raw = cleaned_text[start + 1 : i]
        line_no = cleaned_text.count("\n", 0, m.start()) + 1
        oneline = " ".join(args_raw.split())
        out.append((line_no, name, oneline, args_raw))
    return out


WANTED = {
    "target_link_libraries",
    "include_directories",
    "add_definitions",
    "add_compile_options",
    "link_directories",
    "link_libraries",
    "set",
    "string",
    "file",
    "add_library",
    "add_executable",
    "target_sources",
    "target_compile_features",
    "if",
    "elseif",
    "while",
    "foreach",
    "message",
    "option",
    "target_compile_options",
    "target_compile_definitions",
}

FLAGS_VAR_RE = re.compile(r"\bCMAKE_(C|CXX)_FLAGS\b")
CXX_STD_SET_RE = re.compile(r"^\s*CMAKE_CXX_STANDARD\b")
GLOB_KEYWORD_RE = re.compile(r"^(GLOB|GLOB_RECURSE)\b", re.IGNORECASE)
UNQUOTED_VAR_COMPARE_RE = re.compile(
    r"(?<![A-Za-z0-9_}])\$\{[A-Za-z_][A-Za-z0-9_]*\}(?![A-Za-z0-9_{])"
    r"[^\"]{0,40}?\b(STREQUAL|MATCHES|EQUAL|VERSION_(LESS|GREATER|EQUAL)[A-Z_]*)\b"
)
QUOTED_BEFORE_RE = re.compile(r'"\s*\$\{[A-Za-z_][A-Za-z0-9_]*\}\s*"')
BARE_FOREACH_RE = re.compile(
    r"^\s*[A-Za-z_][A-Za-z0-9_]*\s+\$\{[A-Za-z_][A-Za-z0-9_]*\}\s*$"
)
GENEXPR_RE = re.compile(r"\$<")
WERROR_RE = re.compile(r"(-Werror\b|/WX\b)")
CMAKE_PREFIXED_VAR_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*")


def toolchain_ish(relpath):
    low = relpath.lower()
    return "toolchain" in low or low.startswith("cmake/toolchains" + os.sep)


def main():
    per_repo = defaultdict(lambda: defaultdict(int))
    exclusions = defaultdict(lambda: defaultdict(int))
    examples = defaultdict(list)  # axis -> list of citation strings (capped)
    EXAMPLE_CAP = 40

    def add_example(axis, repo, relpath, line, snippet):
        if len(examples[axis]) < EXAMPLE_CAP:
            examples[axis].append(f"{repo}:{relpath}:{line}: {snippet}")

    file_count = defaultdict(int)
    vendored_file_count = defaultdict(int)
    generated_file_count = defaultdict(int)
    kitware_excluded_count = 0

    for repo, relpath, full in iter_files():
        if is_kitware_excluded(repo, relpath):
            kitware_excluded_count += 1
            continue
        vendored = is_vendored(relpath)
        scaffold = is_scaffold(relpath)
        try:
            with open(full, "r", errors="replace") as fh:
                raw = fh.read()
        except OSError:
            continue

        head = "\n".join(raw.split("\n")[:40])
        generated = bool(GENERATED_BANNER_RE.search(head))
        if generated:
            generated_file_count[repo] += 1
            exclusions[repo]["generated_files"] += 1
            continue
        if vendored:
            vendored_file_count[repo] += 1

        bucket = "vendored" if vendored else ("scaffold" if scaffold else "core")
        file_count[repo] += 1

        lines = raw.split("\n")
        cleaned = "\n".join(strip_comment(l) for l in lines)

        calls = extract_calls(cleaned, WANTED)

        # per-file state for M-E-10 dataflow approximation
        glob_result_vars = {}  # varname -> (line, had_configure_deps)

        for line_no, name, oneline, raw_args in calls:
            lname = name.lower()

            # ---- M-E-01: target_link_libraries keyword discipline ----
            if lname == "target_link_libraries":
                per_repo[(repo, bucket)]["tll_total"] += 1
                tokens = oneline.split()
                has_keyword = any(t in TARGET_KEYWORDS for t in tokens[1:4])
                if not has_keyword:
                    per_repo[(repo, bucket)]["tll_bare"] += 1
                    add_example(
                        "M-E-01", repo, relpath, line_no,
                        f"target_link_libraries({oneline[:90]})",
                    )

            # ---- M-E-02: directory-scoped commands ----
            elif lname in DIRECTORY_SCOPED:
                per_repo[(repo, bucket)][f"dirscoped_{lname}"] += 1
                if len(examples.get(f"M-E-02-{lname}", [])) < 10:
                    add_example(
                        f"M-E-02-{lname}", repo, relpath, line_no,
                        f"{lname}({oneline[:80]})",
                    )

            # ---- M-E-03: CMAKE_*_FLAGS mutation ----
            elif lname == "set" and FLAGS_VAR_RE.search(oneline.split()[0] if oneline else ""):
                key = "flags_set_toolchain" if toolchain_ish(relpath) else "flags_set_nontoolchain"
                per_repo[(repo, bucket)][key] += 1
                if key == "flags_set_nontoolchain":
                    add_example("M-E-03", repo, relpath, line_no, f"set({oneline[:90]})")
            elif lname == "string":
                stoks = oneline.split()
                if stoks and stoks[0].upper() == "APPEND" and len(stoks) > 1 and FLAGS_VAR_RE.search(stoks[1]):
                    key = "flags_append_toolchain" if toolchain_ish(relpath) else "flags_append_nontoolchain"
                    per_repo[(repo, bucket)][key] += 1
                    if key == "flags_append_nontoolchain":
                        add_example("M-E-03", repo, relpath, line_no, f"string({oneline[:90]})")
                # ---- M-C-07 (string) ----
                if GENEXPR_RE.search(raw_args):
                    per_repo[(repo, bucket)]["genexpr_in_string"] += 1
                    add_example("M-C-07-string", repo, relpath, line_no, f"string({oneline[:90]})")

            # ---- M-E-04: CMAKE_CXX_STANDARD ----
            elif lname == "set" and oneline.split() and oneline.split()[0] == "CMAKE_CXX_STANDARD":
                per_repo[(repo, bucket)]["cxx_standard_set"] += 1
                add_example("M-E-04-set", repo, relpath, line_no, f"set({oneline[:90]})")

            elif lname == "target_compile_features":
                if re.search(r"\bcxx_std_\d\d\b", oneline) and "PUBLIC" in oneline.split():
                    per_repo[(repo, bucket)]["compile_features_cxx_std_public"] += 1
                elif re.search(r"\bcxx_std_\d\d\b", oneline):
                    per_repo[(repo, bucket)]["compile_features_cxx_std_other"] += 1

            # ---- M-E-10: file(GLOB...) ----
            elif lname == "file":
                toks = oneline.split()
                if toks and GLOB_KEYWORD_RE.match(toks[0]):
                    has_cd = "CONFIGURE_DEPENDS" in toks
                    # result variable is the token right after the GLOB keyword
                    resvar = toks[1] if len(toks) > 1 else None
                    key = "glob_with_configure_deps" if has_cd else "glob_without_configure_deps"
                    per_repo[(repo, bucket)][key] += 1
                    if resvar:
                        glob_result_vars[resvar] = (line_no, has_cd)
                    add_example(
                        "M-E-10", repo, relpath, line_no,
                        f"file({oneline[:90]})" + (" [CONFIGURE_DEPENDS]" if has_cd else ""),
                    )
                # generator expressions inside file(...) -- not part of M-C-07's
                # named commands (message/if/string) but file(GENERATE) is the
                # correct sink, so file(WRITE ...$<...>) is worth flagging too.
                if toks and toks[0].upper() == "WRITE" and GENEXPR_RE.search(raw_args):
                    per_repo[(repo, bucket)]["genexpr_in_file_write"] += 1
                    add_example("M-C-07-file-write", repo, relpath, line_no, f"file({oneline[:90]})")

            elif lname in ("add_library", "add_executable", "target_sources"):
                for resvar, (gline, has_cd) in glob_result_vars.items():
                    if resvar in oneline.split() or f"${{{resvar}}}" in oneline:
                        key = "glob_feeds_target_with_cd" if has_cd else "glob_feeds_target_without_cd"
                        per_repo[(repo, bucket)][key] += 1
                        break

            # ---- M-E-11: literal -Werror / WX ----
            elif lname in ("target_compile_options", "add_compile_options"):
                if WERROR_RE.search(oneline):
                    per_repo[(repo, bucket)]["werror_literal"] += 1
                    add_example("M-E-11", repo, relpath, line_no, f"{lname}({oneline[:90]})")

            # ---- M-C-03: unquoted var in if/elseif/while comparisons ----
            elif lname in ("if", "elseif", "while"):
                per_repo[(repo, bucket)][f"{lname}_total"] += 1
                stripped_quoted = QUOTED_BEFORE_RE.sub('"Q"', raw_args)
                if UNQUOTED_VAR_COMPARE_RE.search(stripped_quoted):
                    per_repo[(repo, bucket)]["unquoted_if_compare"] += 1
                    add_example(
                        "M-C-03-unquoted-if", repo, relpath, line_no,
                        f"{lname}({oneline[:90]})",
                    )

            elif lname == "foreach":
                per_repo[(repo, bucket)]["foreach_total"] += 1
                if BARE_FOREACH_RE.match(oneline):
                    per_repo[(repo, bucket)]["foreach_bare"] += 1
                    add_example("M-C-03-bare-foreach", repo, relpath, line_no, f"foreach({oneline[:90]})")

            # ---- M-C-07: message() ----
            elif lname == "message":
                if GENEXPR_RE.search(raw_args):
                    per_repo[(repo, bucket)]["genexpr_in_message"] += 1
                    add_example("M-C-07-message", repo, relpath, line_no, f"message({oneline[:90]})")

            # ---- M-C-09: option() prefix ----
            elif lname == "option":
                toks = oneline.split()
                if toks:
                    optname = toks[0].strip('"')
                    per_repo[(repo, bucket)]["option_total"] += 1
                    if optname.upper().startswith("CMAKE_"):
                        per_repo[(repo, bucket)]["option_cmake_prefixed"] += 1
                        add_example("M-C-09-cmake-prefixed", repo, relpath, line_no, f"option({oneline[:90]})")
                    per_repo[(repo, bucket)][f"__optname__{optname}"] = 1  # tracked separately below

        # CMAKE_CXX_STANDARD paired _REQUIRED/_EXTENSIONS: a light per-file
        # regex scan, since correlating sibling set() calls needs no more
        # than "does this file also set the pairing variable".
        req_hits = len(re.findall(r"set\(\s*CMAKE_CXX_STANDARD_REQUIRED\s+ON", cleaned))
        ext_off_hits = len(re.findall(r"set\(\s*CMAKE_CXX_STANDARD_EXTENSIONS\s+OFF", cleaned))
        std_hits = len(re.findall(r"set\(\s*CMAKE_CXX_STANDARD\s+\d+", cleaned))
        if std_hits:
            per_repo[(repo, bucket)]["cxx_standard_required_on_infile"] += (1 if req_hits else 0)
            per_repo[(repo, bucket)]["cxx_standard_extensions_off_infile"] += (1 if ext_off_hits else 0)
            per_repo[(repo, bucket)]["cxx_standard_files_with_set"] += 1

    # collapse per-repo option name sets into distinct-prefix stats
    option_names = defaultdict(set)
    for (repo, bucket), d in per_repo.items():
        for k in list(d.keys()):
            if k.startswith("__optname__"):
                option_names[(repo, bucket)].add(k[len("__optname__"):])
                del d[k]

    def dominant_prefix(names):
        pref_count = defaultdict(int)
        for n in names:
            if "_" in n:
                pref_count[n.split("_")[0].upper()] += 1
        if not pref_count:
            return None, 0
        best = max(pref_count.items(), key=lambda kv: kv[1])
        return best[0], best[1]

    for (repo, bucket), names in option_names.items():
        pfx, cnt = dominant_prefix(names)
        d = per_repo[(repo, bucket)]
        d["option_distinct_names"] = len(names)
        d["option_dominant_prefix"] = pfx or ""
        d["option_dominant_prefix_count"] = cnt
        unprefixed = 0
        for n in names:
            if pfx and not n.upper().startswith(pfx + "_"):
                unprefixed += 1
            elif not pfx:
                unprefixed += 1
        d["option_unprefixed_estimate"] = unprefixed

    # ---- emit ----
    with open(os.path.join(OUT_DIR, "per_repo_counts.json"), "w") as f:
        json.dump(
            {
                f"{repo}|{bucket}": dict(d)
                for (repo, bucket), d in per_repo.items()
            },
            f,
            indent=1,
            sort_keys=True,
        )

    with open(os.path.join(OUT_DIR, "examples.json"), "w") as f:
        json.dump(examples, f, indent=1, sort_keys=True)

    with open(os.path.join(OUT_DIR, "exclusions_summary.json"), "w") as f:
        json.dump(
            {
                "kitware_tests_help_files_excluded": kitware_excluded_count,
                "generated_files_excluded_per_repo": dict(generated_file_count),
                "vendored_files_by_repo": dict(vendored_file_count),
                "firstparty_plus_vendored_files_scanned_by_repo": dict(file_count),
            },
            f,
            indent=1,
            sort_keys=True,
        )

    print("done", file=sys.stderr)


if __name__ == "__main__":
    main()
